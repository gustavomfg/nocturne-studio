function isLanguage(value: unknown): value is Language {
  return value === 'pt-BR' || value === 'en'
}

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return DEFAULT_LANGUAGE
  try {
    const stored = window.localStorage.getItem('nocturne.language')
    return isLanguage(stored) ? stored : DEFAULT_LANGUAGE
  } catch {
    return DEFAULT_LANGUAGE
  }
}

export function getCurrentLanguage(): Language {
  if (typeof document === 'undefined') return DEFAULT_LANGUAGE
  return isLanguage(document.documentElement.lang) ? document.documentElement.lang : DEFAULT_LANGUAGE
}

export function translate(language: Language, key: string, values: Record<string, string | number> = {}) {
  const template = messages[language][key] ?? messages[DEFAULT_LANGUAGE][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? `{${name}}`))
}

interface I18nContextValue {
  language: Language
  setLanguage(language: Language): void
  t(key: string, values?: Record<string, string | number>): string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage)
  const setLanguage = (next: Language) => {
    setLanguageState(next)
    try { window.localStorage.setItem('nocturne.language', next) } catch { /* preference remains in memory */ }
  }
  useEffect(() => { document.documentElement.lang = language }, [language])
  const value = useMemo<I18nContextValue>(() => ({ language, setLanguage, t: (key, values) => translate(language, key, values) }), [language])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('I18nProvider ausente.')
  return value
}

export function isSupportedLanguage(value: unknown): value is Language {
  return isLanguage(value)
}
